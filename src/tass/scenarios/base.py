"""Minimal public extension interface; plugins own their domain rules."""

from typing import Protocol

from tass.config import ScenarioConfig
from tass.types import Action, Decision, Observation
from tass.world import World


class ScenarioPlugin(Protocol):
    def build_world(self, config: ScenarioConfig) -> World: ...
    def restore_world(self, config: ScenarioConfig, snapshot: dict) -> World: ...
    def begin_tick(self, world: World) -> None: ...
    def observe(self, world: World, actor_id: str) -> Observation: ...
    def tools(self, world: World, actor_id: str) -> dict[str, str]: ...
    def resolve(self, world: World, decisions: dict[str, Decision]) -> None: ...
    def end_tick(self, world: World) -> None: ...
    def metrics(self, world: World) -> dict: ...
    def baseline(self, world: World, actor_id: str, observation: Observation) -> list[Action]: ...
